#!/usr/bin/env python3
"""Convert a ProTracker MOD to a song for sdk/src/modplay.c (modplay.h).

The song is unrolled row by row (the order list, 64 rows a pattern; Fxx
below 32 sets the speed). Each MOD channel is routed to an AY channel of a
TurboSound chip, and each sample becomes an instrument:

  --route 0=0A,1=0B,2=1A,3=1B      MOD channel = chip + AY channel (A/B/C);
                                   unrouted channels aren't played
  --inst 1=tone:11                 sample 1: a tone at volume 11 that holds
  --inst 7=tone:11:6               ...that drops 1 every 6 frames
  --inst 6=tone:10:2:1             ...drops 1 every 2 frames (decay:step)
  --inst 3=kick:13:1:2:220:250     a falling tone: volume 13, -2 a frame,
                                   period +220 a frame from 250
  --inst 4=noise:12:1:1:10         noise: volume 12, -1 a frame, period 10
  --clock 1750000                  the AY clock (the Next's; a 128K: 1773400)

Pitch: a sample's notes are its loop's frequency: 3546895 / (MOD period x
samples a cycle). Samples a cycle is measured from the waveform (the loop's
if it has one: zero crossings); --cycle 6=44 overrides it.

    python3 sdk/tools/mod2ay.py song.mod --name my_song --route ... --inst ... > src/my_song.c
"""
import argparse
import sys

PAL = 3546895


def load(path):
    d = open(path, "rb").read()
    samples = []
    off = 1084 + (max(d[952:952 + 128]) + 1) * 1024
    for i in range(31):
        s = d[20 + i * 30:50 + i * 30]
        ln = int.from_bytes(s[22:24], "big") * 2
        ls, ll = int.from_bytes(s[26:28], "big") * 2, int.from_bytes(s[28:30], "big") * 2
        data = d[off:off + ln]
        samples.append(data[ls:ls + ll] if ll > 2 else data)     # a loop: its waveform, else the whole
        off += ln
    return d, samples


def cycle_of(data):
    """samples a cycle: the length over the upward zero crossings (wrapping round)"""
    v = [b - 256 if b > 127 else b for b in data]
    up = sum(1 for a, b in zip(v, v[1:] + v[:1]) if a < 0 <= b)
    return len(v) / up if up else 32


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mod")
    ap.add_argument("--name", required=True)
    ap.add_argument("--route", required=True)
    ap.add_argument("--inst", action="append", default=[])
    ap.add_argument("--cycle", action="append", default=[])
    ap.add_argument("--clock", type=int, default=1750000)
    a = ap.parse_args()
    d, samples = load(a.mod)
    route = {}
    for r in a.route.split(","):
        c, dest = r.split("=")
        route[int(c)] = (int(dest[0]), "ABC".index(dest[1].upper()))
    insts, inst_of = [], {}
    for spec in a.inst:
        smp, desc = spec.split("=")
        f = desc.split(":")
        kind = {"tone": 0, "noise": 1, "kick": 2}[f[0]]
        vol = int(f[1])
        decay = int(f[2]) if len(f) > 2 else 0
        step = int(f[3]) if len(f) > 3 else 1
        param = int(f[4]) if len(f) > 4 else 0
        start = int(f[5]) if len(f) > 5 else 0
        inst_of[int(smp)] = (len(insts), kind, start)
        insts.append((kind, vol, decay, step, param))
    cycles = {i + 1: cycle_of(s) for i, s in enumerate(samples) if s}
    for spec in a.cycle:
        smp, n = spec.split("=")
        cycles[int(smp)] = float(n)
    songlen = d[950]
    speed = 6
    voices = [[] for _ in range(4)]
    rows = []
    last_smp = [0] * 4
    for o in d[952:952 + songlen]:
        for r in range(64):
            out = []
            for c in range(4):
                b = d[1084 + o * 1024 + r * 16 + c * 4:][:4]
                smp = (b[0] & 0xF0) | (b[2] >> 4)
                per = ((b[0] & 0x0F) << 8) | b[1]
                if b[2] & 0x0F == 0x0F and b[3] and b[3] < 32:
                    speed = b[3]
                if smp:
                    last_smp[c] = smp
                smp = smp or last_smp[c]
                if not per or c not in route or smp not in inst_of:
                    out.append(0)
                    continue
                idx, kind, start = inst_of[smp]
                period = start if kind == 2 else 0 if kind == 1 else round(a.clock / 16 * per * cycles[smp] / PAL)
                v = (period, idx)
                if v not in voices[c]:
                    voices[c].append(v)
                out.append(voices[c].index(v) + 1)
            rows.append(out)
    n = a.name
    p = print
    p(f"/* generated by sdk/tools/mod2ay.py from {a.mod.split('/')[-1]} - do not edit */")
    p("#include <stdint.h>")
    p('#include "modplay.h"')
    p()
    p(f"static const mod_inst {n}_inst[{len(insts)}] = {{")
    for kind, vol, decay, step, param in insts:
        p(f"    {{{kind}, {vol}, {decay}, {step}, {param}}},")
    p("};")
    for c in range(4):
        if voices[c]:
            p(f"static const mod_voice {n}_v{c}[{len(voices[c])}] = {{ " + ", ".join("{%d,%d}" % v for v in voices[c]) + " };")
    p(f"static const uint8_t {n}_rows[{len(rows) * 4}] = {{")
    for i in range(0, len(rows), 8):
        p("    " + " ".join("%d,%d,%d,%d," % tuple(r) for r in rows[i:i + 8]))
    p("};")
    vptr = ", ".join(f"{n}_v{c}" if voices[c] else "0" for c in range(4))
    rt = ", ".join(f"MOD_ROUTE({route[c][0]}, {route[c][1]})" if c in route else "0xFF" for c in range(4))
    p(f"const mod_song {n} = {{ {len(rows)}, {speed}, {n}_rows, {{ {vptr} }}, {n}_inst, {{ {rt} }} }};")


if __name__ == "__main__":
    main()
