#!/usr/bin/env python3
"""Pictures for the Spectrum Next: Layer 2 screens and sprite patterns.

As a library (import nextpic) or a command:

  nextpic.py l2 pic.png --mode 320 --bank 30 --out gfx/title
      a 320 x 256 (or --mode 256: 256 x 192) indexed or RGB PNG ->
      gfx/title_<k>.bin (16K banks), gfx/title.asm (BANK_n sections that put
      them into the .nex: assemble it with the program, then NextReg 0x12 =
      bank shows it, see nextgfx.h l2w_init), gfx/title_pal.c (the palette,
      9-bit RGB333, `const uint16_t <name>_pal[256]`)
  nextpic.py sprites sheet.png --out gfx/spr [--quad]
      a sheet of 16 x 16 cells (or 32 x 32 with --quad: four patterns each,
      TL TR BL BR for spr_show_quad) -> gfx/spr.bin; transparent: index 0xE3
      or alpha 0

RGB pictures are reduced to the Next's 9-bit colours (at most 256 of them).
"""
import argparse
import os
import sys

from PIL import Image

TRANSPARENT = 0xE3


def rgb9(c12):
    """12-bit Amiga RGB (0xRGB) -> the Next's 9-bit RGB333"""
    r, g, b = (c12 >> 8) & 15, (c12 >> 4) & 15, c12 & 15
    return (r >> 1) << 6 | (g >> 1) << 3 | (b >> 1)


def rgb9_from_rgb(r, g, b):
    return (r * 7 + 127) // 255 << 6 | (g * 7 + 127) // 255 << 3 | (b * 7 + 127) // 255


def rgb_from_rgb9(c):
    return tuple(((c >> s) & 7) * 255 // 7 for s in (6, 3, 0))


def avoid_transparent(pal):
    """Layer 2 hides pixels whose colour's top 8 bits are 0xE3: nudge such entries"""
    return [c ^ 2 if (c >> 1) == TRANSPARENT else c for c in pal]


def indexed(img):
    """(pixels as indices, 256-entry 9-bit palette) from a P or RGB image"""
    if img.mode == "P":
        raw = img.getpalette()[:768]
        raw += [0] * (768 - len(raw))
        pal = [rgb9_from_rgb(*raw[i * 3:i * 3 + 3]) for i in range(256)]
        return img, avoid_transparent(pal)
    rgb = img.convert("RGB")
    colours, idx = {}, Image.new("P", rgb.size)
    src, dst = rgb.load(), idx.load()
    for y in range(rgb.height):
        for x in range(rgb.width):
            c = rgb9_from_rgb(*src[x, y])
            if c not in colours:
                if len(colours) == 256:
                    sys.exit("more than 256 colours after reducing to RGB333")
                colours[c] = len(colours)
            dst[x, y] = colours[c]
    pal = [0] * 256
    for c, i in colours.items():
        pal[i] = c
    return idx, avoid_transparent(pal)


def l2_bytes(img, mode):
    """Layer 2 memory: 320 mode is column-major (x * 256 + y), 256 mode row-major"""
    w, h = (320, 256) if mode == 320 else (256, 192)
    if img.size != (w, h):
        sys.exit(f"the picture is {img.size}, mode {mode} needs {w} x {h}")
    p = img.load()
    if mode == 320:
        return bytes(p[x, y] for x in range(w) for y in range(h))
    return bytes(p[x, y] for y in range(h) for x in range(w))


def write_banks(data, bank, out, asm_file=True):
    """16K pieces out_<k>.bin and (asm_file) out.asm putting them in BANK_bank.. sections"""
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    asm = [f"; generated by sdk/tools/nextpic.py: {os.path.basename(out)} in banks {bank}.. of the .nex"]
    for k in range(0, len(data), 16384):
        name = f"{out}_{k // 16384}.bin"
        open(name, "wb").write(data[k:k + 16384])
        asm += [f"SECTION BANK_{bank + k // 16384}", f'BINARY "{name}"']
    if asm_file:
        open(out + ".asm", "w").write("\n".join(asm) + "\n")


def write_palette_c(pal, name, path):
    rows = [", ".join(str(c) for c in pal[i:i + 16]) for i in range(0, 256, 16)]
    open(path, "w").write(f"/* generated by sdk/tools/nextpic.py */\n#include <stdint.h>\nconst uint16_t {name}_pal[256] = {{\n    "
                          + ",\n    ".join(rows) + "\n};\n")


def patterns(img, quad=False):
    """16 x 16 patterns from a sheet (indices; alpha 0 -> 0xE3); quad: 32 x 32 cells as TL TR BL BR"""
    cell = 32 if quad else 16
    if img.mode == "RGBA":
        alpha = img.getchannel("A").load()
        idx, _ = indexed(img.convert("RGB"))
    else:
        alpha, idx = None, img
    p = idx.load()
    out = []
    for cy in range(0, img.height - cell + 1, cell):
        for cx in range(0, img.width - cell + 1, cell):
            for qy, qx in ((0, 0), (0, 16), (16, 0), (16, 16))[:4 if quad else 1]:
                out.append([TRANSPARENT if alpha and alpha[cx + qx + x, cy + qy + y] == 0 else p[cx + qx + x, cy + qy + y]
                            for y in range(16) for x in range(16)])
    return out


def quad_patterns(pix32):
    """a 32 x 32 list of indices -> four 16 x 16 patterns: TL TR BL BR"""
    return [[pix32[(qy + y) * 32 + qx + x] for y in range(16) for x in range(16)] for qy in (0, 16) for qx in (0, 16)]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("what", choices=["l2", "sprites"])
    ap.add_argument("picture")
    ap.add_argument("--out", required=True)
    ap.add_argument("--mode", type=int, default=320, choices=[256, 320])
    ap.add_argument("--bank", type=int, default=30)
    ap.add_argument("--quad", action="store_true")
    a = ap.parse_args()
    img = Image.open(a.picture)
    if a.what == "l2":
        idx, pal = indexed(img)
        write_banks(l2_bytes(idx, a.mode), a.bank, a.out)
        write_palette_c(pal, os.path.basename(a.out), a.out + "_pal.c")
        print(f"{a.out}: {a.mode} mode, banks {a.bank}..")
    else:
        pats = patterns(img, a.quad)
        os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
        open(a.out + ".bin", "wb").write(bytes(sum(pats, [])))
        print(f"{a.out}.bin: {len(pats)} patterns")


if __name__ == "__main__":
    main()
