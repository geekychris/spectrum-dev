#!/usr/bin/env python3
"""src/music_song.c from the original's MOD ("Tower Climb", assets/stack_tower.mod,
made by amiga_mcp's tools/modgen/stack_tower.py) through sdk/tools/mod2ay.py.

The four MOD channels on TurboSound chips 1 and 2 (lead, bass and organ on
chip 1, the drums on chip 2's A); chip 0 is left to the effects.

    python3 tools/make_music.py
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from gen_gfx import MUSIC_BANK  # noqa: E402
ROOT = HERE.parents[2]
c = subprocess.run([sys.executable, str(ROOT / "sdk/tools/mod2ay.py"), str(HERE.parent / "assets" / "stack_tower.mod"),
                    "--name", "st_song", "--route", "0=1A,1=1B,2=1C,3=2A",
                    "--inst", "1=tone:12:3",          # bell lead: decays
                    "--inst", "2=tone:12:4",          # pluck bass
                    "--inst", "3=tone:8",             # organ: holds
                    "--inst", "4=kick:13:1:2:220:250",
                    "--inst", "5=noise:11:1:1:8",     # snare
                    "--inst", "6=noise:7:1:2:2"],     # hat
                   check=True, capture_output=True, text=True).stdout
c = c.replace("generated by sdk/tools/mod2ay.py", "generated by tools/make_music.py (sdk/tools/mod2ay.py)")

# the rows (1,280 bytes) go to a bank of their own, read through MMU slot 0
# while the player ticks (sound.c): main memory is full
m = re.search(r"static const uint8_t st_song_rows\[(\d+)\] = \{(.*?)\};\n", c, re.S)
rows = bytes(int(v) for v in re.findall(r"\d+", m.group(2)))
assert len(rows) == int(m.group(1))
(HERE.parent / "sound").mkdir(exist_ok=True)
(HERE.parent / "sound" / "rows_0.bin").write_bytes(rows + bytes(16384 - len(rows)))
(HERE.parent / "src" / "music_data.asm").write_text(
    "; generated by tools/make_music.py - do not edit: the song's rows, in a bank\n"
    f"SECTION BANK_{MUSIC_BANK}\nBINARY \"sound/rows_0.bin\"\n")
c = c.replace(m.group(0), f"/* the rows ({len(rows)} bytes) are in bank {MUSIC_BANK}, at 0x0000 when it is mapped into slot 0 */\n")
c = c.replace("st_song_rows,", "(const uint8_t *)0x0000,")
c += f"\nconst uint8_t st_song_page = {MUSIC_BANK * 2};\n"
(HERE.parent / "src" / "music_song.c").write_text(c)
