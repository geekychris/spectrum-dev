#!/usr/bin/env python3
"""Convert stakattack.mod (the original's ProTracker music) to src/music.c.

The song is unrolled row by row (12 orders x 64 rows, speed 5 = 5 frames a
row) into four bytes per row, one per MOD channel:

  ch0 lead, ch1 bass  -> TurboSound AY 0, channels A and B
  ch2 kick/snare/hat  -> AY 1 channel A (tone sweep / noise)
  ch3 stab/bell       -> AY 1 channel B

A byte is 0 for "no new note", else an index + 1 into the channel's AY
period table (ch2: 1 kick, 2 snare, 3 hat; ch3: bit 7 set = bell).

Pitch: the samples are single-cycle loops (lead and bell 32 samples per
cycle, bass 64, stab 44), so the note frequency is 3546895 / (period *
samples_per_cycle) and the AY period (1.75 MHz / 16) is 109375 / f.

    python3 tools/mod2ay.py tools/stakattack.mod > src/music.c
"""
import sys

PAL = 3546895
AY = 1750000 / 16
CYCLE = {1: 32, 2: 64, 6: 44, 7: 32}


def main(path):
    d = open(path, "rb").read()
    songlen = d[950]
    order = list(d[952:952 + songlen])
    speed = 6
    rows = []
    for o in order:
        for r in range(64):
            row = []
            for c in range(4):
                b = d[1084 + o * 1024 + r * 16 + c * 4:][:4]
                smp = (b[0] & 0xF0) | (b[2] >> 4)
                per = ((b[0] & 0x0F) << 8) | b[1]
                if b[2] & 0x0F == 0x0F and b[3] < 32:
                    speed = b[3]
                row.append((smp, per))
            rows.append(row)
    tables = {0: [], 1: [], 3: []}
    out = []
    for row in rows:
        enc = []
        for c, (smp, per) in enumerate(row):
            if not per:
                enc.append(0)
            elif c == 2:
                enc.append({3: 1, 4: 2, 5: 3}[smp])
            else:
                ayp = round(AY * per * CYCLE[smp] / PAL)
                t = tables[c]
                if ayp not in t:
                    t.append(ayp)
                v = t.index(ayp) + 1
                enc.append(v | (0x80 if smp == 7 else 0))
        out.append(enc)
    p = print
    p("/* generated by tools/mod2ay.py from tools/stakattack.mod - do not edit */")
    p("#include <stdint.h>")
    p('#include "music.h"')
    p()
    for c, name in ((0, "lead"), (1, "bass"), (3, "ch3")):
        p(f"const uint16_t music_{name}_period[] = {{ {', '.join(map(str, tables[c]))} }};")
    p(f"const uint8_t music_speed = {speed};")
    p(f"const uint8_t music_rows[{len(out)}][4] = {{")
    for i in range(0, len(out), 4):
        p("    " + " ".join("{%d,%d,%d,%d}," % tuple(r) for r in out[i:i + 4]))
    p("};")


if __name__ == "__main__":
    main(sys.argv[1])
