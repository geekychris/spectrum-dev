#!/usr/bin/env python3
"""Pea Shooter Blast's sound effects for the Next's TurboSound.

The original (main.c build_sfx) synthesises six 8-bit samples and plays
them with ptplayer's mt_playfx: a square wave whose frequency is
rate x step / 256 (the sample `((i * step) & 0xFF) > 128`), a linear
envelope, some with noise, at the period and volume given there. Here each
becomes an AY register stream on chip 2 (sdk aystream.h): the same start
and end frequencies, envelope and noise, frame by frame.
port: the samples last 5-45 ms; an AY stream changes once a frame (20 ms),
so each lasts at least two frames.

The music is the original's MOD (src/music.c, sdk/tools/mod2ay.py, see
tools/make_assets.sh).

    python3 tools/gen_sound.py        (from projects/pea_shooter_blast)
Output: sound/bank_36.bin, src/sound_data.asm, src/sound_data.c/.h.
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "..", "..", "sdk", "tools"))
from aystream import Ay, encode, period  # noqa: E402

FIRST_BANK = 36
PAULA = 3546895

# build_sfx: (name, samples, period, volume 0..64, step start, step end,
# envelope start, end (0..127), noise share 0..1)
SFX = [
    ("shoot", 128, 180, 50, 25, 25, 127, 0, 0.0),
    ("hit", 96, 200, 40, 35, 35, 127, 0, 0.3),
    ("explode", 512, 300, 64, 0, 0, 127, 0, 1.0),
    ("powerup", 256, 250, 50, 15, 45, 100, 40, 0.0),
    ("jump", 128, 200, 35, 30, 10, 80, 0, 0.0),
    ("player_hit", 256, 300, 60, 10, 35, 127, 0, 0.5),
    ("key", 128, 200, 40, 40, 40, 100, 0, 0.0),      # port: a letter taken in the initials
]


def vol(a):
    """amplitude 0..1 -> AY volume (about 3 dB a step)"""
    return 0 if a <= 0.01 else max(0, min(15, int(round(15 + 2 * math.log2(a)))))


def stream(n, per, v, s0, s1, e0, e1, noise):
    rate = PAULA / per
    frames = max(2, int(math.ceil(n / rate * 50)))
    ay = Ay()
    for f in range(frames):
        t = (f + 0.5) / frames
        step = s0 + (s1 - s0) * t
        env = (e0 + (e1 - e0) * t) / 127
        a = env * v / 64
        if noise >= 1:
            ay.noise(0, 4, vol(a))
        elif noise > 0:
            ay.tone_noise(0, period(rate * step / 256), 6, vol(a))
        else:
            ay.tone(0, period(rate * step / 256), vol(a))
        ay.frame()
    ay.off(0)
    ay.frame()
    return encode(ay)


def main():
    data, where = bytearray(), []
    for name, *args in SFX:
        b = stream(*args)
        where.append((name, FIRST_BANK * 2 + len(data) // 8192, 0x4000 + len(data) % 8192, len(b)))
        data += b
    data += bytes((-len(data)) % 16384)
    os.makedirs(os.path.join(ROOT, "sound"), exist_ok=True)
    open(os.path.join(ROOT, "sound", f"bank_{FIRST_BANK}.bin"), "wb").write(bytes(data))
    with open(os.path.join(ROOT, "src", "sound_data.asm"), "w") as f:
        f.write(f"; generated by tools/gen_sound.py - do not edit: the effects' AY streams\n\n"
                f"SECTION BANK_{FIRST_BANK}\nBINARY \"sound/bank_{FIRST_BANK}.bin\"\n")
    with open(os.path.join(ROOT, "src", "sound_data.h"), "w") as f:
        f.write("/* generated by tools/gen_sound.py - do not edit */\n#ifndef SOUND_DATA_H\n#define SOUND_DATA_H\n"
                "#include <stdint.h>\n/* a stream: 8K page, address with the page in MMU slot 2 */\n"
                "typedef struct { uint8_t page; uint16_t addr; } Stream;\n"
                f"extern const Stream sfx_streams[{len(SFX)}];\n"
                "enum { " + ", ".join(f"SFX_{n.upper()}" for n, *_ in SFX) + ", SFX_COUNT };\n#endif\n")
    with open(os.path.join(ROOT, "src", "sound_data.c"), "w") as f:
        f.write('/* generated by tools/gen_sound.py - do not edit */\n#include "sound_data.h"\n\n'
                f"const Stream sfx_streams[{len(SFX)}] = {{\n")
        for name, page, addr, ln in where:
            f.write(f"    {{ {page}, 0x{addr:04X} }},   /* {name}: {ln} bytes */\n")
        f.write("};\n")
    print(f"{len(SFX)} effects, {sum(w[3] for w in where)} bytes")


if __name__ == "__main__":
    main()
