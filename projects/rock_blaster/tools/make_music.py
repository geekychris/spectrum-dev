#!/usr/bin/env python3
"""src/music_song.c from the original's MOD (sdk/tools/mod2ay.py): the lead
(brass) and the bass on AY channels B and C of a 128K; channel A is left for
the effects (the original kept two of Paula's channels for effects).

The song's row table (2 KB, half of it the unused channels' zeros) is
packed with sdk/tools/zxrle.py and unpacked at start-up into the RAM below
the program (src/lowmem.h)."""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "sdk" / "tools"))
from zxrle import pack, unpack  # noqa: E402

c = subprocess.run([sys.executable, str(ROOT / "sdk/tools/mod2ay.py"), str(HERE / "rock_blaster.mod"),
                    "--name", "rb_song", "--route", "0=0B,1=0C", "--inst", "1=tone:11:4",
                    "--inst", "2=tone:12:3", "--clock", "1773400"],
                   check=True, capture_output=True, text=True).stdout
m = re.search(r"static const uint8_t rb_song_rows\[(\d+)\] = \{(.*?)\};\n", c, re.S)
rows = bytes(int(v) for v in re.findall(r"\d+", m.group(2)))
assert len(rows) == int(m.group(1))
packed = pack(rows)
assert unpack(packed) == rows
lines = ",\n".join("    " + ",".join(str(b) for b in packed[i:i + 24]) for i in range(0, len(packed), 24))
c = c.replace(m.group(0), f"/* the rows ({len(rows)} bytes) packed with sdk/tools/zxrle.py */\n"
              f"static const uint8_t rb_song_rows_rle[{len(packed)}] = {{\n{lines}\n}};\n")
c = c.replace('#include "modplay.h"\n', '#include "modplay.h"\n#include "zxrle.h"\n#include "lowmem.h"\n')
c = c.replace("rb_song_rows,", "(const uint8_t *)LOW_SONG_ROWS,")
c += "\nvoid rb_music_init(void)\n{\n    rle_unpack((uint8_t *)LOW_SONG_ROWS, rb_song_rows_rle);\n}\n"
c = c.replace("generated by sdk/tools/mod2ay.py", "generated by tools/make_music.py (sdk/tools/mod2ay.py)")
(HERE.parent / "src" / "music_song.c").write_text(c)
print(f"rows {len(rows)} -> {len(packed)} bytes packed")
