def sin_tab(i):
    i &= 255
    if i <= 64:
        return SIN[i]
    if i <= 128:
        return SIN[128 - i]
    return -sin_tab(i - 128)


def a3_sin(a):
    i, f = (a >> 8) & 255, a & 255
    s0, s1 = sin_tab(i), sin_tab(i + 1)
    return s0 + (((s1 - s0) * f) >> 8)


def trunc_div(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


class Model:
    def __init__(self, name):
        self.name, self.v, self.f = name, [], []

    def vtx(self, x, y, z):
        self.v.append((x, y, z))
        return len(self.v) - 1

    def face(self, lit, shade, n, a, b, c, d, ix, iy, iz):
        A, B, C = self.v[a], self.v[b], self.v[c]
        ux, uy, uz = B[0] - A[0], B[1] - A[1], B[2] - A[2]
        vx, vy, vz = C[0] - A[0], C[1] - A[1], C[2] - A[2]
        nx, ny, nz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
        if nx * (A[0] - ix) + ny * (A[1] - iy) + nz * (A[2] - iz) >= 0:
            idx = [a, b, c, d]
        else:
            idx = [d, c, b, a] if n == 4 else [c, b, a, 0]
            nx, ny, nz = -nx, -ny, -nz
        light = -nx + 2 * ny + nz
        mag = abs(nx) + abs(ny) + abs(nz)
        # the outward plane, for culling in model space: n . e > d faces the eye e
        g = max(abs(nx), abs(ny), abs(nz)) or 1
        k = 64 / g
        qn = (round(nx * k), round(ny * k), round(nz * k))
        A = self.v[idx[0]]
        d = qn[0] * A[0] + qn[1] * A[1] + qn[2] * A[2]
        self.f.append((n, idx, lit if (mag and light * 4 > mag * 3) else shade, qn, d))

    def box(self, lit, shade, x0, x1, y0, y1, z0, z1):
        b, cx, cy, cz = len(self.v), trunc_div(x0 + x1, 2), trunc_div(y0 + y1, 2), trunc_div(z0 + z1, 2)
        for p in ((x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
                  (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)):
            self.vtx(*p)
        for q in ((0, 3, 2, 1), (5, 6, 7, 4), (4, 7, 3, 0), (1, 2, 6, 5), (3, 7, 6, 2), (0, 1, 5, 4)):
            self.face(lit, shade, 4, *(b + k for k in q), cx, cy, cz)

    def pyramid(self, lit, shade, x0, x1, y0, z0, z1, apex):
        b, cx, cz = len(self.v), trunc_div(x0 + x1, 2), trunc_div(z0 + z1, 2)
        cy = y0 + trunc_div(apex - y0, 4)
        for p in ((x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)):
            self.vtx(*p)
        t = self.vtx(cx, apex, cz)
        for k in range(4):
            self.face(lit, shade, 3, b + k, b + (k + 1) % 4, t, 0, cx, cy, cz)

    def prism(self, lit, shade, sides, r, y0, y1):
        b, cy = len(self.v), trunc_div(y0 + y1, 2)
        for k in range(sides):
            a = (k * 65536) // sides
            x, z = (a3_sin(a) * r) >> 16, (a3_sin(a + 16384) * r) >> 16
            self.vtx(x, y0, z)
            self.vtx(x, y1, z)
        for k in range(sides):
            j = (k + 1) % sides
            self.face(lit, shade, 4, b + 2 * k, b + 2 * k + 1, b + 2 * j + 1, b + 2 * j, 0, cy, 0)
        c = self.vtx(0, y1, 0)
        for k in range(sides):
            j = (k + 1) % sides
            self.face(lit, lit, 3, b + 2 * k + 1, b + 2 * j + 1, c, 0, 0, y0, 0)


PEN_SHIELD = 22
