int32_t a3_sin(uint16_t a)
{
    uint8_t i = (uint8_t)(a >> 8), f = (uint8_t)a;
    int32_t s0 = sin_tab[i], s1 = sin_tab[(uint8_t)(i + 1)];
    return s0 + (mul16((int16_t)(s1 - s0), f) >> 8);
}

/* a3_atan_ratio: num, den >= 0 here (a3_atan2 passes magnitudes) */
static uint16_t atan_ratio(uint32_t a, uint32_t den)
{
    uint32_t t;
    uint8_t f;
    if (!den) return 0;
    if (a > den) a = den;
    while (den > 0x7FFFF) { a >>= 1; den >>= 1; }      /* a * 2048 must fit */
    t = (a << 11) / den;                                /* 1/16 steps of the table */
    f = (uint8_t)t & 15;
    t >>= 4;
    return atan_tab[t] + (t < 128 ? (uint16_t)(((atan_tab[t + 1] - atan_tab[t]) * f) >> 4) : 0);
}

/* the angle of (x, y) from +y towards +x, 16-bit (a3d_math.c a3_atan2) */
uint16_t a3_atan2(int32_t x, int32_t y)
{
    uint32_t ax = x < 0 ? -x : x, ay = y < 0 ? -y : y;
    uint16_t a;
    if (!ax && !ay) return 0;
    if (ax <= ay) a = atan_ratio(ax, ay);
    else a = 16384 - atan_ratio(ay, ax);
    if (y < 0) a = 32768 - a;
    if (x < 0) a = -a;
    return a;
}

/* sqrt(a*a + b*b), scaled down until the squares fit (a3d_fix.c) */
fix fhypot(fix a, fix b)
{
    uint32_t x = (uint32_t)(a < 0 ? -a : a), y = (uint32_t)(b < 0 ? -b : b);
    uint8_t sh = 0;
    while ((x | y) >= 46000) { x >>= 1; y >>= 1; sh++; }
    return (fix)((uint32_t)isqrt32(x * x + y * y) << sh);
}

/* floor(a * b / 65536) cut to 32 bits, from 16-bit halves:
   a * b = ah bh 2^32 + (ah bl + al bh) 2^16 + al bl */
fix fmul(fix a, fix b)
{
    int16_t ah = (int16_t)(a >> 16), bh = (int16_t)(b >> 16);
    uint16_t al = (uint16_t)a, bl = (uint16_t)b;
    uint32_t r = (uint32_t)mul16(ah, bh) << 16;
    r += (uint32_t)((int32_t)ah * (int32_t)bl);
    r += (uint32_t)((int32_t)bh * (int32_t)al);
    r += ((uint32_t)al * bl) >> 16;
    return (fix)r;
}

/* (a * 65536) / b, truncated towards 0 and cut to 32 bits: a 48 by 32 bit
   division (td_obs.asm on the Z80) */
#ifndef __SDCC
fix fdiv(fix a, fix b)
{
    uint32_t n = (uint32_t)(a < 0 ? -a : a), d = (uint32_t)(b < 0 ? -b : b), q = 0, r = 0;
    uint8_t i;
    for (i = 0; i < 48; i++) {
        r = (r << 1) | (n >> 31);
        n <<= 1;
        q <<= 1;
        if (r >= d) { r -= d; q |= 1; }
    }
    return (a < 0) != (b < 0) ? -(fix)q : (fix)q;
}
#endif
