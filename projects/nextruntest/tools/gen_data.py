#!/usr/bin/env python3
"""The test images for nextruntest (src/img_data.c): shapes encoded with
sdk/tools/runimg.py. test.py draws the same shapes with runimg.decode and
compares them with what l2wr_blit put in Layer 2.

    python3 projects/nextruntest/tools/gen_data.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "sdk" / "tools"))
from runimg import encode  # noqa: E402


def shape():
    """40 x 60: a wedge (offsets 0, 1, 2 in bands), a gap in some columns
    (two runs), a run longer than the blitter's 25 (split), an empty column"""
    h, w = 60, 40
    off = [[0] * w for _ in range(h)]
    opq = [[False] * w for _ in range(h)]
    for x in range(w):
        if x == 17:
            continue                            # an empty column inside
        top, bot = x // 2, 30 + x // 3
        for y in range(top, bot + 1):
            if 5 <= x < 10 and y in (top + 3, top + 4):
                continue                        # a gap: two runs
            opq[y][x] = True
            off[y][x] = (y - top) % 3
    return off, opq


def main():
    data = encode(*shape())
    rows = ",\n    ".join(", ".join(str(b) for b in data[i:i + 16]) for i in range(0, len(data), 16))
    (HERE.parent / "src" / "img_data.c").write_text(
        "/* generated by tools/gen_data.py - do not edit */\n#include <stdint.h>\n"
        f"const uint8_t test_img[{len(data)}] = {{\n    {rows}\n}};\n")


if __name__ == "__main__":
    main()
