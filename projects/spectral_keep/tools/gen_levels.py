#!/usr/bin/env python3
"""src/levels.c from the original's levels.c (tools/orig, itself generated
from the Unity project's level JSON): the same rooms, cells and actors.

port: each room's cells (MAXH x d x w bytes, mostly '.') are packed with
sdk/tools/zxrle.py and unpacked by room_build (24 rooms: 10 KB -> about 1.5
KB, so the levels fit in the main memory); each keep gets its first room's
place in the room pictures (gen_gfx.py makes them in the same order) and its
number of relics (the original counts them when a keep starts).

    python3 tools/gen_levels.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "..", "..", "sdk", "tools"))
from zxrle import pack  # noqa: E402

src = open(os.path.join(HERE, "orig", "levels.c")).read()
body = src[src.index('#include "keep.h"') + len('#include "keep.h"'):]
cells = dict(re.findall(r'static const char cells_(\d+_\d+)\[\] = "([^"]*)";', body))
packed = 0


def cells_c(m):
    global packed
    data = pack(m.group(2).encode())
    packed += len(data)
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return (f"static const uint8_t cells_{m.group(1)}[] = {{   /* {len(m.group(2))} bytes packed */\n    "
            + ",\n    ".join(rows) + "\n};")


body = re.sub(r'static const char cells_(\d+_\d+)\[\] = "([^"]*)";', cells_c, body)
first = 0


def level(m):
    global first
    k, nrooms = m.group(2), int(m.group(3))
    relics = sum(c.count("R") for key, c in cells.items() if key.startswith(k + "_"))
    out = f"{m.group(1)}{nrooms}, {first}, {relics} }}"
    first += nrooms
    return out


body = re.sub(r"(\{ \"[^\"]+\", \d+, \d+, \d+, \d+, \d+, rooms_(\d+), )(\d+) \}", level, body)
body = body.replace("const int keep_nlevels", "const uint8_t keep_nlevels")
with open(os.path.join(ROOT, "src", "levels.c"), "w") as f:
    f.write("/* generated by tools/gen_levels.py from the original's levels.c - do not edit */\n"
            '#include "keep.h"' + body)
print(f"src/levels.c: {first} rooms, cells packed to {packed} bytes")
