#!/usr/bin/env python3
"""tools/orig/test_cases.c (the original's tests) -> src/test_cases.c, the
in-game self-test, with the two changes the port needs (marked port:)."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
src = open(os.path.join(HERE, "orig", "test_cases.c")).read()
src = src.replace('"../bb.h"', '"bb.h"').replace('"vectors.h"', '"../tools/orig/vectors.h"')
# zsdcc compiled `g->nev = 0;` after these three into "LD L,H; LD (nev),HL",
# taking H to be 0 still (it held the capsule's y): nev became -1
old = "    g->stuck = 1;\n    g->px = g->cap[0].x;\n    g->py = g->cap[0].y;\n    g->nev = 0;\n"
new = ("    g->nev = 0;                         /* port: first (zsdcc stored a stale register for it last) */\n"
       "    g->stuck = 1;\n    g->px = g->cap[0].x;\n    g->py = g->cap[0].y;\n")
assert old in src
src = src.replace(old, new)
head = ("/* generated by tools/port_tests.py from tools/orig/test_cases.c (the original's\n"
        "   tests/test_cases.c) - do not edit; changes marked port: */\n")
open(os.path.join(ROOT, "src", "test_cases.c"), "w").write(head + src)
