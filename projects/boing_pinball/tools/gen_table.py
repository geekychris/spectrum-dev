#!/usr/bin/env python3
"""Boing Pinball's tables for the Spectrum Next, from the original's.

tools/export_table (the original pb_tables.c, built on the host) writes each
table as JSON; this turns one into src/table_<n>.c in the Z80 units of
src/pbz.h (P = 1/16 mm, V = 1/4 mm/s, Q14 unit vectors, A = 1/4096 rad).

    python3 tools/gen_table.py build/host/table_0.json 0 > src/table_0.c
"""
import json
import math
import sys

P = lambda v: int(round(v * 16))
V = lambda v: int(round(v * 4))
A = lambda v: int(round(v * 4096))
Q14 = lambda v: int(round(v * 16384))
R_BALL = 13.5


def seg_row(s):
    ax, ay, bx, by, r, e, kind, sid, owx, owy, bank, h, up = s
    ex, ey = bx - ax, by - ay
    ln = math.hypot(ex, ey)
    ux, uy = (ex / ln, ey / ln) if ln > 0 else (0, 0)
    grow = r + R_BALL + 4
    bb = [P(min(ax, bx) - grow), P(min(ay, by) - grow), P(max(ax, bx) + grow) + 16, P(max(ay, by) + grow) + 16]
    return ("{%d,%d,%d,%d, %d,%d, %d,%d, {%d,%d,%d,%d}, %d, %d,%d,%d,%d,%d, 1}"
            % (P(ax), P(ay), P(bx), P(by), Q14(ux), Q14(uy), P(ln), P(r), *bb,
               min(255, int(round(e * 256))), kind, sid, owx, owy, bank))


def main(path, n):
    d = json.load(open(path))
    out = []
    p = out.append
    p(f"/* generated by tools/gen_table.py from the original's {d['name']} - do not edit */")
    p('#include "pbz.h"')
    p("")
    p(f"static Seg seg[{len(d['seg'])}] = {{")
    for s in d["seg"]:
        p("    " + seg_row(s) + ",")
    p("};")
    p(f"static const Circ circ[{len(d['circ'])}] = {{")
    for cx, cy, r, e, bumper, cid, h in d["circ"]:
        p(f"    {{{P(cx)},{P(cy)},{P(r)}, {min(255, int(round(e * 256)))}, {bumper},{cid}}},")
    p("};")
    p(f"static const Sensor sens[{len(d['sens'])}] = {{")
    for ax, ay, bx, by, kind, idx in d["sens"]:
        grow = R_BALL + 4
        bb = [P(min(ax, bx) - grow), P(min(ay, by) - grow), P(max(ax, bx) + grow) + 16, P(max(ay, by) + grow) + 16]
        p(f"    {{{P(ax)},{P(ay)},{P(bx)},{P(by)}, {{{bb[0]},{bb[1]},{bb[2]},{bb[3]}}}, {kind},{idx}}},")
    p("};")
    p(f"static const FlipDef flip[{len(d['flip'])}] = {{")
    for side, px, py, ln, r1, r2, rest, up in d["flip"]:
        p(f"    {{{side}, {P(px)},{P(py)}, {P(ln)}, {P(r1)},{P(r2)}, {A(rest)},{A(up)}}},")
    p("};")
    p(f"static const Ramp ramp[{max(1, len(d['ramp']))}] = {{")
    for r in d["ramp"]:
        pts = ", ".join("{%d,%d,%d}" % tuple(q) for q in r["pts"])
        prof = ", ".join(str(P(v)) for v in r["prof"])
        ex, ey, evy = r["exit"]
        p(f"    {{{len(r['pts'])}, {{{pts}}}, {{{prof}}}, {P(ex)},{P(ey)},{V(evy)}}},")
    p("};")
    p(f"static const SpinDef spin[{max(1, len(d['spin']))}] = {{ " + ", ".join("{%d,%d}" % (P(x), P(y)) for x, y in d["spin"]) + " };")
    p(f"static const int8_t drop_seg[{max(1, d['ndrop'])}] = {{ " + ", ".join(map(str, d["drop_seg"])) + " };")
    starts, entries = [], []
    for row in d["grid"]:
        for cell in row:
            starts.append(len(entries))
            entries += cell
    starts.append(len(entries))
    p(f"static const uint16_t grid_at[{len(starts)}] = {{ " + ", ".join(map(str, starts)) + " };")
    p(f"static const uint16_t grid[{len(entries)}] = {{ " + ", ".join(map(str, entries)) + " };")
    missions = ", ".join('"%s"' % m for m in d["mission"])
    sx, sy, sr = d["saucer"]
    px, prest = d["plunger"]
    p("")
    p(f"Table table_{n} = {{")
    p(f'    "{d["name"]}", {{ {missions} }},')
    p(f"    {len(d['seg'])}, {len(d['circ'])}, {len(d['sens'])}, {len(d['flip'])}, {len(d['ramp'])}, {len(d['spin'])}, {d['ndrop']},")
    p("    seg, circ, sens, flip, ramp, spin, drop_seg,")
    p(f"    {P(sx)}, {P(sy)}, {P(sr)}, {P(px)}, {P(prest)},")
    p("    grid_at, grid")
    p("};")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
