#!/usr/bin/env python3
"""src/music_song.c from the original's MOD (art/terra_strike.mod, "patrol
drive", the same file as amiga_mcp/examples/terra_strike/terra_strike.mod)
through sdk/tools/mod2ay.py.

The MOD's four channels on TurboSound chips 1 and 2: the arpeggio / lead /
stab, the rolling bass and the drums on chip 1, the hats on chip 2's A;
chip 0 is left to the effects. The song is compiled into the HUD's bank
(bank 26, Makefile), which is mapped while sound.c ticks the player.

    python3 tools/make_music.py
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
c = subprocess.run([sys.executable, str(ROOT / "sdk/tools/mod2ay.py"), str(HERE.parent / "art" / "terra_strike.mod"),
                    "--name", "ts_song", "--route", "0=1A,1=1B,2=1C,3=2A",
                    "--inst", "1=tone:9:3",           # arp: plucked
                    "--inst", "2=tone:12:5",          # rolling bass
                    "--inst", "3=kick:13:1:2:220:250",
                    "--inst", "4=kick:13:1:2:220:250",  # kick + clap
                    "--inst", "5=noise:6:1:2:1",      # hat
                    "--inst", "6=noise:6:1:1:2",      # open hat
                    "--inst", "7=tone:10",            # saw lead: holds
                    "--inst", "8=noise:11:1:1:8",     # snare
                    "--inst", "9=tone:11:2"],         # stab
                   check=True, capture_output=True, text=True).stdout
c = c.replace("generated by sdk/tools/mod2ay.py", "generated by tools/make_music.py (sdk/tools/mod2ay.py)")
(HERE.parent / "src" / "music_song.c").write_text(c)
