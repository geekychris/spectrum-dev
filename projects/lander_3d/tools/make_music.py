#!/usr/bin/env python3
"""The original's music ("Quiet Descent", tools/orig/lander_3d.mod, made by
amiga_mcp's tools/modgen) for the SDK's modplay, through sdk/tools/mod2ay.py:
its four channels on TurboSound chips 1 and 2 (the glass arpeggio, the drone
and the air pad on chip 1, the pulse on chip 2's A); chip 0 is the effects'.
Run by the Makefile:

    python3 tools/make_music.py OUTDIR      -> OUTDIR/music_song.c, OUTDIR/music_rows.bin

The rows go to bank MUSIC_BANK (sound.h), read through MMU slot 0 while the
player ticks.
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
MUSIC_BANK = 26
out = Path(sys.argv[1])
c = subprocess.run([sys.executable, str(ROOT / "sdk/tools/mod2ay.py"), str(HERE / "orig" / "lander_3d.mod"),
                    "--name", "ld_song", "--route", "0=1A,1=1B,2=1C,3=2A",
                    "--inst", "1=tone:11:5",          # glass arp: rings out
                    "--inst", "2=tone:9",             # drone: holds
                    "--inst", "3=tone:7",             # air pad: soft, holds
                    "--inst", "4=tone:10:2"],         # pulse: short
                   check=True, capture_output=True, text=True).stdout
c = c.replace("generated by sdk/tools/mod2ay.py", "generated by tools/make_music.py (sdk/tools/mod2ay.py)")
m = re.search(r"static const uint8_t ld_song_rows\[(\d+)\] = \{(.*?)\};\n", c, re.S)
rows = bytes(int(v) for v in re.findall(r"\d+", m.group(2)))
assert len(rows) == int(m.group(1)) and len(rows) <= 16384
(out / "music_rows.bin").write_bytes(rows + bytes(16384 - len(rows)))
c = c.replace(m.group(0), f"/* the rows ({len(rows)} bytes) are in bank {MUSIC_BANK}, at 0x0000 when it is mapped into slot 0 */\n")
c = c.replace("ld_song_rows,", "(const uint8_t *)0x0000,")
(out / "music_song.c").write_text(c)
