/*
 * gen_world.c - Orb Hunter's world, made by the original's own levels.c
 * (amiga_mcp examples/orb_hunter, compiled as it is with tools/shim):
 *
 *   gfx/world.bin       world_rooms[6][8][16][20] (15,360 bytes), a room
 *                       every 320 bytes: the game copies it into a bank
 *   src/items_data.c    the item table place_items() fills
 *
 *   make -C tools world      (ORIG=path to the original)
 */
#include <stdio.h>
#include "game.h"

int main(int argc, char **argv)
{
    FILE *f;
    WORD i;
    if (argc < 3) return 2;
    levels_init();
    f = fopen(argv[1], "wb");
    fwrite(world_rooms, 1, sizeof(world_rooms), f);
    fclose(f);
    f = fopen(argv[2], "w");
    fprintf(f, "/* generated by tools/gen_world.c from the original's levels.c - do not edit */\n"
               "#include \"game.h\"\n\n/* place_items(): room x, y, tile x, y, type */\n"
               "const ItemSpawn items_start[%d] = {\n", g_num_items);
    for (i = 0; i < g_num_items; i++)
        fprintf(f, "    { %d, %d, %d, %d, %d, 0 },\n", g_items[i].room_x, g_items[i].room_y, g_items[i].tile_x,
                g_items[i].tile_y, g_items[i].type);
    fprintf(f, "};\nconst WORD items_count = %d;\n", g_num_items);
    fclose(f);
    return 0;
}
