#!/usr/bin/env python3
"""src/music_song.c from the original's music: Orb Hunter plays
rock_blaster.mod on two channels (main.c: mt_MusicChannels = 2), converted
by sdk/tools/mod2ay.py with Rock Blaster's instruments, both channels on
TurboSound chip 1 (chip 0 is left to the effects). The rows go to bank
MUSIC_BANK (read through MMU slot 0 while the player ticks, sound.c).

    python3 tools/make_music.py
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
MUSIC_BANK = 24                         # src/banks.h
c = subprocess.run([sys.executable, str(ROOT / "sdk/tools/mod2ay.py"), str(HERE.parent / "assets" / "rock_blaster.mod"),
                    "--name", "oh_song", "--route", "0=1A,1=1B", "--inst", "1=tone:11:4", "--inst", "2=tone:12:3"],
                   check=True, capture_output=True, text=True).stdout
c = c.replace("generated by sdk/tools/mod2ay.py", "generated by tools/make_music.py (sdk/tools/mod2ay.py)")
m = re.search(r"static const uint8_t oh_song_rows\[(\d+)\] = \{(.*?)\};\n", c, re.S)
rows = bytes(int(v) for v in re.findall(r"\d+", m.group(2)))
assert len(rows) == int(m.group(1)) and len(rows) <= 16384
(HERE.parent / "sound" / "rows_0.bin").write_bytes(rows + bytes(16384 - len(rows)))
(HERE.parent / "src" / "music_data.asm").write_text(
    "; generated by tools/make_music.py - do not edit: the song's rows, in a bank\n"
    f"SECTION BANK_{MUSIC_BANK}\nBINARY \"sound/rows_0.bin\"\n")
c = c.replace(m.group(0), f"/* the rows ({len(rows)} bytes) are in bank {MUSIC_BANK}, at 0x0000 when mapped into slot 0 */\n")
c = c.replace("oh_song_rows,", "(const uint8_t *)0x0000,")
(HERE.parent / "src" / "music_song.c").write_text(c)
print(f"{len(rows)} bytes of rows")
